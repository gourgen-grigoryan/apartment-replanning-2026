def draw_walls(d):
    for wall in d['walls']:
        a, b = wall['a'], wall['b']
        u = [b[j]-a[j] for j in (0,1)]
        def on_axis(p):
            return sum((p[j]-a[j])*u[j] for j in (0,1))/sum(t*t for t in u)
        spans = []
        for opening in d['openings']:
            if opening['wall'] == wall['id']:
                lo,hi = sorted(on_axis(opening[k]) for k in ('a','b'))
                spans.append((max(0,lo), min(1,hi), opening))
        prev = 0
        for lo,hi,o in sorted(spans,key=lambda s:s[0])+[(1,1,None)]:
            if lo>prev:
                world([cut(a,b,prev),cut(a,b,lo)],teal if wall['kind']=='new' else ink,wall['t']*S)
            prev=max(prev,hi)
            if o is None:
                continue
            a1,b1 = cut(a,b,lo),cut(a,b,hi)
            if 'window' in o['kind'] or o['kind']=='glazed_door':
                world([a1,b1], '#438994', 2)
            if o['kind'] in ('door','entry','entry_common','glazed_door'):
                pivot = cut(a,b,on_axis(o[o['hinge']]))
                other = cut(a,b,on_axis(o['b' if o['hinge']=='a' else 'a']))
                dx,dy=o['swing']; radius=math.dist(a1,b1)
                world([pivot,(pivot[0]+radius*dx,pivot[1]+radius*dy)],grey,.9)
                theta=math.atan2(other[1]-pivot[1],other[0]-pivot[0])
                step=(math.atan2(dy,dx)-theta+math.pi)%(2*math.pi)-math.pi
                world([(pivot[0]+radius*math.cos(theta+step*j/16),pivot[1]+radius*math.sin(theta+step*j/16)) for j in range(17)],grey,.65,dash=(2,2))

