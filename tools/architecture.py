def dim(a,b,t=None,off=9):
    if t is None:
        t=str(round(math.dist(a,b)*1000))
    a,b=xy(a),xy(b);length=math.dist(a,b)
    u=((b[0]-a[0])/length,(b[1]-a[1])/length);n=(-u[1],u[0])
    p=tuple(a[j]+off*n[j] for j in (0,1));q=tuple(b[j]+off*n[j] for j in (0,1))
    line(a,p,grey,.55);line(b,q,grey,.55);line(p,q,grey,.55)
    for x,y in (p,q):
        line((x-2,y-2.5),(x+2,y+2.5),grey,.65)
    C.saveState();C.translate((p[0]+q[0])/2,(p[1]+q[1])/2)
    angle=math.degrees(math.atan2(u[1],u[0]));C.rotate(angle if abs(angle)<=90 else angle+180)
    txt(0,3,t,8,ink,'bold','center');C.restoreState()

